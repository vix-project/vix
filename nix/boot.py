"""Generation-based GRUB configuration; never installs a bootloader."""

import base64
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tempfile


HEADER = "# Generated by Vix; edit your machine flake.\n"


class BootError(Exception):
    pass


def sync_directory(directory):
    fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def atomic_file(path, contents, mode=0o644):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(contents)
            stream.flush()
            os.fchmod(stream.fileno(), mode)
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        sync_directory(path.parent)
    finally:
        Path(temporary).unlink(missing_ok=True)


class BootManager:
    def __init__(self, boot_directory="/boot"):
        self.directory = Path(boot_directory)
        self.grub = self.directory / "grub/grub.cfg"
        self.original = self.directory / "grub/grub.cfg.vix-original"

    @staticmethod
    def load(system):
        if system is None or not (Path(system) / "boot").exists():
            return None
        try:
            descriptor = json.loads((Path(system) / "boot/boot.json").read_text())
            if descriptor["format"] != 1:
                raise ValueError("unsupported format")
            if not re.fullmatch(r"[a-zA-Z0-9_.+-]+", descriptor["kernel_version"]):
                raise ValueError("invalid kernel version")
            if not re.fullmatch(r"[a-zA-Z0-9_./=:+-]+", descriptor["root_device"]):
                raise ValueError("invalid root device")
            if not isinstance(descriptor["kernel_params"], list) or not all(
                isinstance(p, str)
                and "\n" not in p
                and "\r" not in p
                and not p.startswith(("root=", "vix.generation="))
                for p in descriptor["kernel_params"]
            ):
                raise ValueError("invalid or reserved kernel parameters")
            for key in ("kernel", "initrd"):
                if not Path(descriptor[key]).is_file():
                    raise ValueError(f"{key} is missing")
            modules = (
                Path(descriptor["runtime"]) / "modules" / descriptor["kernel_version"]
            )
            if not modules.is_dir():
                raise ValueError("matching runtime modules are missing")
        except (OSError, ValueError, KeyError, TypeError) as error:
            raise BootError(f"invalid boot generation {system}: {error}") from error
        return descriptor

    def filesystem(self):
        try:
            result = subprocess.run(
                [
                    "findmnt",
                    "--json",
                    "--target",
                    str(self.directory),
                    "--output",
                    "UUID,TARGET",
                ],
                check=True,
                text=True,
                stdout=subprocess.PIPE,
                timeout=10,
            )
            filesystem = json.loads(result.stdout)["filesystems"][0]
            uuid, mountpoint = filesystem["uuid"], filesystem["target"]
            if not uuid or not re.fullmatch(r"[a-zA-Z0-9_-]+", uuid):
                raise ValueError("boot filesystem needs a UUID")
            return uuid, Path(mountpoint)
        except (subprocess.SubprocessError, ValueError, KeyError, IndexError) as error:
            raise BootError(f"cannot identify the boot filesystem: {error}") from error

    def snapshot(self, old_system, system):
        old, new = self.load(old_system), self.load(system)
        if old is None and new is None:
            return None
        if not self.grub.is_file():
            raise BootError(
                "kernel management requires an installed GRUB configuration at /boot/grub/grub.cfg"
            )
        self.filesystem()
        return {
            "contents": base64.b64encode(self.grub.read_bytes()).decode(),
            "mode": self.grub.stat().st_mode & 0o777,
            "symlink": os.readlink(self.grub) if self.grub.is_symlink() else None,
        }

    def restore(self, snapshot):
        if snapshot is None:
            return
        if snapshot["symlink"] is not None:
            temporary = self.grub.with_name(".grub.cfg.vix-restore")
            temporary.unlink(missing_ok=True)
            temporary.symlink_to(snapshot["symlink"])
            os.replace(temporary, self.grub)
            sync_directory(self.grub.parent)
        else:
            atomic_file(
                self.grub, base64.b64decode(snapshot["contents"]), snapshot["mode"]
            )

    def stage(self, system):
        descriptor = self.load(system)
        asset_name = (Path(system) / "boot").resolve().name
        if not re.fullmatch(r"[a-zA-Z0-9_.+-]+", asset_name):
            raise BootError("invalid boot asset name")
        parent = self.directory / "vix/kernels"
        parent.mkdir(parents=True, exist_ok=True)
        destination = parent / asset_name
        if destination.exists():
            for filename in ("kernel", "initrd"):
                original = Path(descriptor[filename])
                installed = destination / filename
                # Boot artifacts are immutable. Do not silently select an
                # incomplete or manually modified directory.
                if (
                    not installed.is_file()
                    or installed.read_bytes() != original.read_bytes()
                ):
                    raise BootError(f"boot artifact was modified: {installed}")
            return destination
        staging = Path(tempfile.mkdtemp(prefix=".vix-new-", dir=parent))
        try:
            for filename in ("kernel", "initrd"):
                target = staging / filename
                with (
                    Path(descriptor[filename]).open("rb") as source,
                    target.open("wb") as output,
                ):
                    shutil.copyfileobj(source, output)
                    output.flush()
                    os.fsync(output.fileno())
            sync_directory(staging)
            os.rename(staging, destination)
            sync_directory(parent)
        finally:
            if staging.exists():
                shutil.rmtree(staging)
        return destination

    def activate(self, system, selected, generations):
        descriptor = self.load(system)
        if descriptor is None:
            if not self.original.is_file():
                raise BootError("the original GRUB configuration is missing")
            atomic_file(self.grub, self.original.read_bytes())
            return
        # A first adoption backs up the currently installed configuration.
        # Subsequent updates preserve that baseline and its fallback entry.
        if not self.grub.read_text().startswith(HEADER):
            atomic_file(self.original, self.grub.read_bytes())
        elif not self.original.is_file():
            raise BootError("the original GRUB configuration is missing")
        uuid, mountpoint = self.filesystem()
        lines = [HEADER.rstrip(), "set default=0", "set timeout=5", ""]
        order = [selected] + sorted(
            (n for n in generations if n != selected), reverse=True
        )
        for number in order:
            generation = generations[number]
            boot = self.load(generation)
            if boot is None:
                continue
            assets = self.stage(generation)
            relative = "/" + assets.relative_to(mountpoint).as_posix()
            title = f"Vix generation {number} (Linux {boot['kernel_version']})"
            parameters = [
                f"root={boot['root_device']}",
                "rw",
                f"vix.generation={number}",
            ] + boot["kernel_params"]
            lines += [
                f"menuentry {shlex.quote(title)} {{",
                f"  search --no-floppy --fs-uuid --set=vix_boot {shlex.quote(uuid)}",
                f"  linux ($vix_boot){shlex.quote(relative + '/kernel')} {shlex.join(parameters)}",
                f"  initrd ($vix_boot){shlex.quote(relative + '/initrd')}",
                "}",
                "",
            ]
        lines += [
            "menuentry 'Vix before declarative kernel management' {",
            '  configfile "$prefix/grub.cfg.vix-original"',
            "}",
            "",
        ]
        # This single rename selects a complete kernel/initramfs pair. The old
        # configuration remains valid until every asset has been copied.
        atomic_file(self.grub, "\n".join(lines).encode())

    def status(self, system):
        descriptor = self.load(system)
        booted_system = Path("/nix/var/nix/gcroots/vix-booted-system")
        if descriptor is None:
            if booted_system.exists():
                return f"kernel: original bootloader selected, running {os.uname().release} (reboot required)\n"
            return ""
        same = (
            (booted_system / "boot").exists()
            and (booted_system / "boot").resolve() == (Path(system) / "boot").resolve()
            and os.uname().release == descriptor["kernel_version"]
        )
        if same:
            try:
                same = os.path.samefile(
                    Path("/lib/modules") / os.uname().release,
                    Path(descriptor["runtime"]) / "modules" / os.uname().release,
                )
            except OSError:
                same = False
        note = "active" if same else "reboot required"
        return f"kernel: configured {descriptor['kernel_version']}, running {os.uname().release} ({note})\n"
